/* Корзина: localStorage */
window.ETRA_CART = {
  read() { try { return JSON.parse(localStorage.getItem('etra_cart') || '[]'); } catch (e) { return []; } },
  write(items) { localStorage.setItem('etra_cart', JSON.stringify(items)); this.refresh(); },
  add(id, qty = 1) {
    const items = this.read();
    const ex = items.find(i => i.id === id);
    if (ex) ex.qty += qty; else items.push({ id, qty });
    this.write(items);
  },
  count() { return this.read().reduce((s, i) => s + i.qty, 0); },
  refresh() {
    document.querySelectorAll('[data-cart-count]').forEach(el => {
      const n = this.count();
      el.textContent = n;
      el.classList.toggle('is-empty', n === 0);
    });
  }
};
